#!/bin/sh

set -eu

verify_script="$(pwd)/infra/scripts/verify-generated.sh"
check_script="$(pwd)/infra/scripts/check-generated.sh"
fixture="$(mktemp -d)"
trap 'rm -rf "$fixture"' EXIT HUP INT TERM
cd "$fixture"
git init -q
mkdir -p gen/go services/aero-identity/internal/storage/sqlc
printf 'baseline\n' > gen/go/fixture.go
printf 'baseline\n' > services/aero-identity/internal/storage/sqlc/fixture.go
git add .
git -c user.name=Fixture -c user.email=fixture@example.invalid commit -qm fixture
sh "$verify_script"
printf 'stale\n' > gen/go/fixture.go
if sh "$verify_script" >/dev/null 2>&1; then
  echo "Stale protobuf output должен отклоняться" >&2
  exit 1
fi
printf 'baseline\n' > gen/go/fixture.go
printf 'stale\n' > services/aero-identity/internal/storage/sqlc/fixture.go
git add services/aero-identity/internal/storage/sqlc/fixture.go
if sh "$verify_script" >/dev/null 2>&1; then
  echo "Staged stale SQL output должен отклоняться" >&2
  exit 1
fi
printf 'baseline\n' > services/aero-identity/internal/storage/sqlc/fixture.go
git add services/aero-identity/internal/storage/sqlc/fixture.go
printf 'new\n' > gen/go/new.go
if sh "$verify_script" >/dev/null 2>&1; then
  echo "Untracked generated output должен отклоняться" >&2
  exit 1
fi
mkdir -p infra/scripts mock-bin services/aero-chat/internal/storage/sqlc services/aero-rtc-control/internal/storage/sqlc
cp "$verify_script" infra/scripts/verify-generated.sh
printf '#!/bin/sh\nexit 0\n' > mock-bin/buf
cp mock-bin/buf mock-bin/sqlc
chmod +x mock-bin/buf mock-bin/sqlc
printf '// Code generated by fixture. DO NOT EDIT.\n' > gen/go/obsolete.go
printf 'package fixture\n' > services/aero-chat/internal/storage/sqlc/manual_test.go
printf 'module fixture\n' > gen/go/go.mod
if PATH="$fixture/mock-bin:$PATH" sh "$check_script" >/dev/null 2>&1; then
  echo "Устаревший output должен приводить к drift" >&2
  exit 1
fi
test ! -f gen/go/obsolete.go
test -f services/aero-chat/internal/storage/sqlc/manual_test.go
test -f gen/go/go.mod
echo "Generated drift negative fixtures passed"
