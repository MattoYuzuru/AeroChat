import { describe, expect, it } from "vitest";
import { historicalWebTimestampAADCandidate } from "./encrypted-aad-timestamp";

describe("historical web timestamp AAD candidate", () => {
  it.each([
    ["2026-03-22T12:00:00Z", "2026-03-22T12:00:00.000Z"],
    ["2026-03-22T12:00:00.1Z", "2026-03-22T12:00:00.100Z"],
    ["2026-03-22T12:00:00.12Z", "2026-03-22T12:00:00.120Z"],
    ["2026-03-22T12:00:00.120000Z", "2026-03-22T12:00:00.120Z"],
    ["2026-03-22T12:00:00.120000000Z", "2026-03-22T12:00:00.120Z"],
    ["2026-03-22T12:00:00.000000000Z", "2026-03-22T12:00:00.000Z"],
    ["0001-01-01T00:00:00Z", "0001-01-01T00:00:00.000Z"],
    ["0099-12-31T23:59:59Z", "0099-12-31T23:59:59.000Z"],
    ["0004-02-29T00:00:00Z", "0004-02-29T00:00:00.000Z"],
    ["1900-02-28T00:00:00Z", "1900-02-28T00:00:00.000Z"],
    ["2000-02-29T00:00:00Z", "2000-02-29T00:00:00.000Z"],
    ["9999-12-31T23:59:59.9Z", "9999-12-31T23:59:59.900Z"],
  ])("recovers only a distinct exact millisecond form for %s", (source, candidate) => {
    expect(historicalWebTimestampAADCandidate(source)).toBe(candidate);
  });

  it.each([
    "2026-03-22T12:00:00.000Z", "2026-03-22T12:00:00.120Z",
    "2026-03-22T12:00:00.123Z", "2026-03-22T12:00:00.120001Z",
    "2026-03-22T12:00:00.120000001Z", "2026-03-22T12:00:00.0001Z",
  ])("does not duplicate raw or round sub-millisecond input %s", (source) => {
    expect(historicalWebTimestampAADCandidate(source)).toBeNull();
  });

  it.each([
    "0000-01-01T00:00:00Z", "10000-01-01T00:00:00Z", "+002026-03-22T12:00:00Z",
    "2026-00-22T12:00:00Z", "2026-13-22T12:00:00Z", "2026-03-00T12:00:00Z",
    "2026-04-31T12:00:00Z", "2026-02-29T12:00:00Z", "1900-02-29T00:00:00Z",
    "0099-02-29T00:00:00Z", "2026-03-22T24:00:00Z", "2026-03-22T12:60:00Z",
    "2026-03-22T12:00:60Z", "2026-03-22T12:00:00+00:00", "2026-03-22T12:00:00z",
    "2026-03-22t12:00:00Z", "2026-03-22T12:00:00.Z", "2026-03-22T12:00:00,12Z",
    "2026-03-22T12:00:00.1200000000Z", " 2026-03-22T12:00:00Z",
    "2026-03-22T12:00:00Z ", "2026-03-22T12:00:00Z\n", "2026-03-22T12:00:00Z\r",
    "2026-03-22T12:00:00Z\u2028", "2026-03-22T12:00:00Z\u2029", "",
  ])("does not offer compatibility for invalid entire timestamp %j", (source) => {
    expect(historicalWebTimestampAADCandidate(source)).toBeNull();
  });
});
